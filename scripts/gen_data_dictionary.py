"""Generate docs/data_dictionary.md from dbt artifacts (manifest + catalog).

    make docs   # runs `dbt docs generate` first

Column types come from the DuckDB catalog; descriptions and tests from the dbt
YAML, so the dictionary always matches what was built.
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
TARGET = REPO_ROOT / "transform" / "target"
DOC = REPO_ROOT / "docs" / "data_dictionary.md"

LAYER_ORDER = ["marts", "seeds", "intermediate", "staging"]


def esc(text: str | None) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def main() -> None:
    manifest = json.loads((TARGET / "manifest.json").read_text())
    catalog = json.loads((TARGET / "catalog.json").read_text())
    cat_nodes = {**catalog.get("nodes", {}), **catalog.get("sources", {})}

    tests_by_col: dict[tuple[str, str], list[str]] = defaultdict(list)
    tests_by_model: dict[str, list[str]] = defaultdict(list)
    for node in manifest["nodes"].values():
        if node["resource_type"] != "test":
            continue
        name = (node.get("test_metadata") or {}).get("name", node["name"])
        attached = node.get("attached_node")
        if not attached:
            continue
        col = node.get("column_name")
        if col:
            tests_by_col[(attached, col)].append(name)
        else:
            tests_by_model[attached].append(name)

    groups: dict[str, list[dict]] = defaultdict(list)
    for uid, node in manifest["nodes"].items():
        if node["resource_type"] not in ("model", "seed"):
            continue
        layer = "seeds" if node["resource_type"] == "seed" else node["fqn"][1]
        groups[layer].append({"uid": uid, **node})

    out = [
        "# Data dictionary",
        "",
        "_Generated by `python -m scripts.gen_data_dictionary` from dbt's `manifest.json` "
        "and `catalog.json`. Do not edit by hand; edit the dbt YAML instead._",
        "",
        "Layers: **marts** (serve these) · **seeds** (crosswalks and reference data) · "
        "**intermediate** · **staging**.",
        "",
    ]
    for layer in LAYER_ORDER:
        nodes = sorted(groups.get(layer, []), key=lambda n: n["name"])
        if not nodes:
            continue
        out += [f"## {layer.title()}", ""]
        for n in nodes:
            uid = n["uid"]
            cat = cat_nodes.get(uid, {})
            cols_cat = cat.get("columns", {})
            stats = cat.get("stats", {})
            rows = stats.get("row_count", {}).get("value") if stats else None
            out += [f"### `{n['name']}`", ""]
            if n.get("description"):
                out += [esc(n["description"]), ""]
            meta_bits = [f"materialized: `{n['config'].get('materialized', 'seed')}`"]
            if rows is not None:
                meta_bits.append(f"rows: {rows:,}")
            if tests_by_model.get(uid):
                meta_bits.append("model tests: " + ", ".join(sorted(set(tests_by_model[uid]))))
            out += [" · ".join(meta_bits), ""]
            out += ["| Column | Type | Description | Tests |", "|---|---|---|---|"]
            names = list(cols_cat) or list(n.get("columns", {}))
            ordered = sorted(names, key=lambda c: cols_cat.get(c, {}).get("index", 0))
            for c in ordered:
                ctype = cols_cat.get(c, {}).get("type", "")
                desc = n.get("columns", {}).get(c, {}).get("description", "")
                tests = ", ".join(sorted(set(tests_by_col.get((uid, c), []))))
                out.append(f"| `{c}` | {ctype} | {esc(desc)} | {tests} |")
            out.append("")
    DOC.write_text("\n".join(out))
    print(f"wrote {DOC.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
